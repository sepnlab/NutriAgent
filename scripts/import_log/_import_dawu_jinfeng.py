def mid(r):
    parts = re.split(r'[~–-]', str(r).replace(' ', '').replace(',',''))
    if len(parts) == 2:
        try: return round((float(parts[0]) + float(parts[1])) / 2, 1)
        except: pass
    try: return float(r.replace(',',''))
    except: return 0

