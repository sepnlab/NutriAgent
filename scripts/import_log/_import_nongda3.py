def mid(range_str):
    """取范围中值，如 '92~94' -> 93.0, '90~94' -> 92.0, '63~67' -> 65.0"""
    parts = range_str.replace("~", "-").replace("–", "-").split("-")
    if len(parts) == 2:
        try:
            return round((float(parts[0]) + float(parts[1])) / 2, 1)
        except ValueError:
            pass
    try:
        return float(range_str)
    except ValueError:
        return ""

