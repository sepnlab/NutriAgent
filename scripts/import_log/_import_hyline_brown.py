def mid(r):
    """Parse '70-80' → 75, '94.8-96.6' → 95.7"""
    import re
    parts = re.split(r'[~–-]', str(r).replace(' ', '').replace('−', '-'))
    if len(parts) == 2:
        try:
            return round((float(parts[0]) + float(parts[1])) / 2, 1)
        except ValueError:
            pass
    try: return float(r)
    except: return 0

