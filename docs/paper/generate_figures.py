def fig6_hallucination_readability():
    methods = ['NutriAgent', 'DS-V4-Pro', 'DS-V4-Flash', 'MiniMax', 'Qwen3-8B', 'Qwen3.5', 'GLM-4.5']
    flesch  = [43.4, 51.2, 51.2, 49.9, 44.5, 40.8, 37.5]
    hall    = [0.117, 0.372, 0.390, 0.340, 0.339, 0.347, 0.423]
    overall = [4.42, 3.77, 3.80, 3.71, 3.11, 3.44, 3.59]

    fig, ax = plt.subplots(figsize=(7, 5))

    sizes = [(o ** 2) * 25 for o in overall]
    colors_bubble = [DBLUE] + [GRAY]*6
    sc = ax.scatter(flesch, hall, s=sizes, c=colors_bubble, alpha=0.7,
                    edgecolors='black', linewidths=0.5, zorder=3)

    x_reg = np.array(flesch[1:])
    y_reg = np.array(hall[1:])
    m, b = np.polyfit(x_reg, y_reg, 1)
    x_line = np.linspace(32, 56, 100)
    ax.plot(x_line, m*x_line + b, '--', color=GRAY, lw=1, alpha=0.6, zorder=2,
            label='Trend (baselines only)')

    # Per-point offsets chosen to avoid label overlap; no normative quadrant labels.
    offsets = {
        'NutriAgent': (-8, 12, 'right'),
        'DS-V4-Pro': (10, 8, 'left'),
        'DS-V4-Flash': (10, -16, 'left'),
        'MiniMax': (-8, -16, 'right'),
        'Qwen3-8B': (-8, 8, 'right'),
        'Qwen3.5': (-8, 8, 'right'),
        'GLM-4.5': (8, 6, 'left'),
    }
    for i, m_name in enumerate(methods):
        ox, oy, ha = offsets[m_name]
        label = f'{m_name}\n({flesch[i]:.1f}, {hall[i]:.3f})'
        ax.annotate(label, (flesch[i], hall[i]), fontsize=FS_ANNOT, xytext=(ox, oy),
                    textcoords='offset points', ha=ha, fontweight='bold' if i==0 else 'normal',
                    linespacing=1.3)

    ax.set_xlabel('Flesch Reading Ease', fontsize=FS_AXIS)
    ax.set_ylabel('SelfCheckGPT-NLI inconsistency score (lower = better)', fontsize=FS_AXIS)
    ax.set_title('Readability–inconsistency trade-off\n(bubble size ~ Overall quality squared)', fontsize=FS_TITLE)
    ax.legend(loc='lower right', fontsize=FS_LEGEND, framealpha=0.9, edgecolor=LGRAY)
    ax.set_xlim(30, 58)
    ax.set_ylim(0.05, 0.48)

    save(fig, 'fig6_hallucination_readability')


