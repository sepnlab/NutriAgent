# Fig 11: Ablation ΔC bar chart
# ============================================================
def fig11_ablation_bar():
    data = [
        ("E1: tools-only vs standalone", -0.32, "−0.32"),
        ("E1: multi-agent vs standalone", +0.20, "+0.20"),
        ("E2: synthesis vs concatenation", +0.63, "+0.63"),
        ("D2: w/o Feed vs Full", +0.22, "+0.22"),
        ("D3: broadcast vs LLM router", -0.04, "−0.04 (n.s.)"),
        ("D4: +RAG vs no RAG", 0.00, "0.00"),
        ("D6: Qwen3-8B vs DS-V4-Flash", -0.80, "−0.80"),
    ]
    labels      = [d[0] for d in data]
    deltas      = [d[1] for d in data]
    annotations = [d[2] for d in data]
    colors      = [GREEN if d > 0 else (RED if d < 0 else GRAY) for d in deltas]

    fig, ax = plt.subplots(figsize=(7, 3.8))
    bars = ax.barh(range(len(labels)), deltas, color=colors,
                   edgecolor='white', height=0.6, zorder=3)

    for i, (bar, delta, ann) in enumerate(zip(bars, deltas, annotations)):
        if delta > 0:
            ax.text(delta + 0.03, i, ann, va='center', ha='left',
                    fontsize=FS_TITLE, fontweight='bold', color=GREEN)
        else:
            ax.text(delta - 0.03, i, ann, va='center', ha='right',
                    fontsize=FS_TITLE, fontweight='bold', color=RED)

    ax.set_yticks(range(len(labels)))
    ax.set_yticklabels(labels, fontsize=FS_TICK)
    ax.set_xlabel('Correctness Change (ΔC) vs Control', fontsize=FS_AXIS)
    ax.axvline(x=0, color=GRAY, linewidth=0.8, zorder=2)
    ax.invert_yaxis()
    ax.set_xlim(-1.1, 1.15)
    ax.grid(axis='x', alpha=0.3, zorder=1)

    legend_elements = [
        mpatches.Patch(facecolor=GREEN, label='Improvement (ΔC > 0)'),
        mpatches.Patch(facecolor=RED,   label='Degradation (ΔC < 0)'),
    ]
    ax.legend(handles=legend_elements, loc='lower right', fontsize=FS_LEGEND,
              framealpha=0.9, edgecolor=LGRAY)
    save(fig, 'fig11_ablation_bar')


